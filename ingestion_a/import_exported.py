"""Import Telegram Desktop chat exports (HTML or JSON) into the SOCMINT database.

Supports two formats generated by Telegram Desktop (Settings → Advanced → Export Chat History):
1. Default HTML export: folders with `messages.html`, `messages2.html`, etc.
2. Machine-Readable JSON export: `result.json` files.

Also provides batch directory scanning to import all exported channels from `Telegram Desktop`
in a single command, auto-discovering channel names, message IDs, timestamps, and reactions.

Usage:
    # Batch import all channels found in Telegram Desktop folder
    python -m ingestion_a.import_exported --import-all-dirs "Telegram Desktop" --max-posts 100 --align-timestamps

    # Import a single HTML chat export folder
    python -m ingestion_a.import_exported --import-dir "Telegram Desktop/ChatExport_2026-10-19" --channel @india_sentinel

    # Import a legacy/machine-readable result.json export
    python -m ingestion_a.import_exported --import-json path/to/result.json --channel @isro_updates

    # Dry-run preview without database changes
    python -m ingestion_a.import_exported --import-all-dirs "Telegram Desktop" --dry-run
"""

from __future__ import annotations

import argparse
import json
import logging
import re
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from sqlalchemy import update
from sqlalchemy.dialects.postgresql import insert as pg_insert

from storage.database import SyncSessionLocal
from storage.models.raw import IngestionRun, MonitoredChannel, RawPost

logger = logging.getLogger("ingestion_a.import_exported")
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(name)s] %(levelname)s: %(message)s",
)


def _extract_text_content(text_field: Any) -> str | None:
    """Extract plain text from Telegram JSON export's text field."""
    if text_field is None:
        return None

    if isinstance(text_field, str):
        return text_field if text_field.strip() else None

    if isinstance(text_field, list):
        parts: list[str] = []
        for element in text_field:
            if isinstance(element, str):
                parts.append(element)
            elif isinstance(element, dict):
                parts.append(element.get("text", ""))
        result = "".join(parts).strip()
        return result if result else None

    return str(text_field) if text_field else None


def _parse_datetime(date_str: str) -> datetime:
    """Parse Telegram JSON ISO datetime string to timezone-aware UTC datetime."""
    try:
        dt = datetime.fromisoformat(date_str)
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt
    except (ValueError, TypeError):
        return datetime.now(timezone.utc)


def _parse_html_datetime(date_str: str) -> datetime:
    """Parse Telegram HTML export date title string (e.g. '10.12.2025 16:51:06 UTC+05:30')."""
    if not date_str:
        return datetime.now(timezone.utc)
    try:
        # Normalize " UTC+05:30" or " UTC" to "+05:30"
        cleaned = re.sub(r"\s+UTC", "", date_str.strip())
        if "+" in cleaned or "-" in cleaned[10:]:
            dt = datetime.strptime(cleaned, "%d.%m.%Y %H:%M:%S%z")
            return dt.astimezone(timezone.utc)
        # Without timezone offset: assume UTC
        dt = datetime.strptime(cleaned, "%d.%m.%Y %H:%M:%S")
        return dt.replace(tzinfo=timezone.utc)
    except Exception:
        try:
            # Fallback simple date "01.12.2021"
            dt = datetime.strptime(date_str.strip()[:10], "%d.%m.%Y")
            return dt.replace(tzinfo=timezone.utc)
        except Exception:
            return datetime.now(timezone.utc)


def _parse_from_id(from_id_str: str | None) -> str | None:
    """Normalize Telegram export from_id field."""
    if not from_id_str:
        return None
    return from_id_str.replace("user", "").replace("channel", "")


def _slugify_channel_name(name: str) -> str:
    """Convert display name (e.g. 'India Sentinel Network') to identifier '@india_sentinel_network'."""
    clean = re.sub(r"[^\w\s-]", "", name).strip().lower()
    clean = re.sub(r"[-\s]+", "_", clean)
    if not clean:
        clean = "channel_" + uuid.uuid4().hex[:6]
    return f"@{clean}"


def _ensure_monitored_channel(session: Any, identifier: str, display_name: str) -> None:
    """Register channel in monitored_channels if not already present."""
    stmt = (
        pg_insert(MonitoredChannel)
        .values(
            identifier=identifier,
            display_name=display_name,
            topic_tags=["osint", "defense", "geopolitics"],
            is_active=True,
            last_polled_at=datetime.now(timezone.utc),
            created_at=datetime.now(timezone.utc),
        )
        .on_conflict_do_nothing(index_elements=["identifier"])
    )
    session.execute(stmt)


# ─── HTML Chat Export Importer ────────────────────────────────────────────────
def import_html_export(
    export_dir: Path,
    channel_id: str | None = None,
    channel_name: str | None = None,
    label: str | None = None,
    max_posts: int | None = None,
    dry_run: bool = False,
) -> int:
    """Parse and import a Telegram Desktop HTML chat export folder.

    Args:
        export_dir: Folder containing messages.html and other messages*.html files.
        channel_id: Optional handle (e.g. '@india_sentinel'). Auto-derived if None.
        channel_name: Optional channel title. Auto-derived if None.
        label: Optional run label.
        max_posts: Optional maximum posts to import (most recent first).
        dry_run: If True, preview without database writes.

    Returns:
        Number of posts imported.
    """
    try:
        from bs4 import BeautifulSoup
    except ImportError:
        logger.error("BeautifulSoup4 is required for HTML chat exports. Run: pip install beautifulsoup4 lxml")
        sys.exit(1)

    if not export_dir.exists() or not export_dir.is_dir():
        logger.error("Export folder not found: %s", export_dir)
        return 0

    # Locate and sort all messages*.html files numerically
    html_files = sorted(
        [f for f in export_dir.glob("messages*.html")],
        key=lambda p: int(re.search(r"messages(\d*)\.html", p.name).group(1) or "1"),
    )

    if not html_files:
        logger.warning("No messages*.html files found in %s", export_dir)
        return 0

    logger.info("Parsing %d HTML files in %s...", len(html_files), export_dir.name)

    # Auto-detect channel title from first messages.html if not provided
    if not channel_name or not channel_id:
        with open(html_files[0], "r", encoding="utf-8", errors="ignore") as f:
            header_soup = BeautifulSoup(f.read(8000), "html.parser")
            h_div = header_soup.find("div", class_="page_header")
            if h_div:
                title_div = h_div.find("div", class_="text bold")
                if title_div:
                    detected_title = title_div.get_text(strip=True)
                    if not channel_name:
                        channel_name = detected_title
                    if not channel_id:
                        channel_id = _slugify_channel_name(detected_title)

    if not channel_name:
        channel_name = export_dir.name
    if not channel_id:
        channel_id = _slugify_channel_name(channel_name)

    # Parse messages across all HTML files
    extracted_posts: list[dict[str, Any]] = []

    for hf in html_files:
        with open(hf, "r", encoding="utf-8", errors="ignore") as f:
            soup = BeautifulSoup(f.read(), "lxml")

        for div in soup.select("div.message.default"):
            text_el = div.find("div", class_="text")
            if not text_el:
                continue
            content_text = text_el.get_text(separator=" ", strip=True)
            if not content_text:
                continue

            raw_id = div.get("id", "").replace("message", "").strip()
            if not raw_id:
                continue

            date_el = div.find("div", class_="date")
            date_title = date_el.get("title", "") if date_el else ""
            posted_at = _parse_html_datetime(date_title)

            # Reactions
            reaction_counts: dict[str, int] = {}
            rx_span = div.find("span", class_="reactions")
            if rx_span:
                for r in rx_span.find_all("span", class_="reaction"):
                    emoji_el = r.find("span", class_="emoji")
                    count_el = r.find("span", class_="count")
                    if emoji_el and count_el:
                        try:
                            reaction_counts[emoji_el.get_text(strip=True)] = int(count_el.get_text(strip=True))
                        except ValueError:
                            pass

            # Reply to
            reply_to_id = None
            rep_div = div.find("div", class_="reply_to")
            if rep_div:
                rep_link = rep_div.find("a")
                if rep_link and rep_link.get("onclick"):
                    m = re.search(r"GoToMessage\((\d+)\)", rep_link["onclick"])
                    if m:
                        reply_to_id = m.group(1)

            # Author name
            from_name_el = div.find("div", class_="from_name")
            from_name = from_name_el.get_text(strip=True) if from_name_el else None

            # Media type
            media_urls = None
            media_div = div.find("div", class_=re.compile(r"media_(photo|video|file)"))
            if media_div:
                media_urls = [{"type": "attachment", "file_id": "desktop_export"}]

            extracted_posts.append({
                "platform_post_id": f"{channel_id}_{raw_id}",
                "channel_id": channel_id,
                "author_id": from_name or channel_id,
                "content_text": content_text,
                "media_urls": media_urls,
                "reply_to_id": reply_to_id,
                "view_count": 0,
                "reaction_counts": reaction_counts or None,
                "posted_at": posted_at,
            })

    # Sort chronological or trim if max_posts is specified
    extracted_posts.sort(key=lambda p: p["posted_at"])
    if max_posts and len(extracted_posts) > max_posts:
        # Keep most recent max_posts
        extracted_posts = extracted_posts[-max_posts:]

    logger.info(
        "Extracted %d valid text posts for channel %s ('%s')",
        len(extracted_posts),
        channel_id,
        channel_name,
    )

    if dry_run:
        logger.info("[DRY RUN] Would import %d posts. No changes written.", len(extracted_posts))
        return len(extracted_posts)

    # Write to database
    session = SyncSessionLocal()
    run_id = uuid.uuid4()

    try:
        _ensure_monitored_channel(session, channel_id, channel_name)

        session.execute(
            pg_insert(IngestionRun).values(
                id=run_id,
                started_at=datetime.now(timezone.utc),
                platform="telegram",
                channel_ids=[channel_id],
                posts_collected=0,
                status="running",
                error_message=label or f"HTML Import from {export_dir.name}",
            )
        )

        imported = 0
        skipped = 0

        for post in extracted_posts:
            stmt = (
                pg_insert(RawPost)
                .values(
                    platform="telegram",
                    platform_post_id=post["platform_post_id"],
                    channel_id=post["channel_id"],
                    author_id=post["author_id"],
                    content_text=post["content_text"],
                    content_language=None,
                    media_urls=post["media_urls"],
                    reply_to_id=post["reply_to_id"],
                    forward_from_id=None,
                    view_count=post["view_count"],
                    reaction_counts=post["reaction_counts"],
                    ingested_at=datetime.now(timezone.utc),
                    posted_at=post["posted_at"],
                    ingestion_run_id=run_id,
                    processing_status="pending",
                )
                .on_conflict_do_nothing(constraint="uq_raw_posts_platform_post_id")
            )

            res = session.execute(stmt)
            if res.rowcount > 0:
                imported += 1
            else:
                skipped += 1

        session.execute(
            update(IngestionRun)
            .where(IngestionRun.id == run_id)
            .values(
                posts_collected=imported,
                status="completed",
                completed_at=datetime.now(timezone.utc),
            )
        )

        session.commit()
        logger.info(
            "Channel %s imported: %d new, %d skipped duplicates (run_id=%s)",
            channel_id,
            imported,
            skipped,
            run_id,
        )
        return imported

    except Exception as exc:
        logger.error("Import error for %s: %s", channel_id, exc, exc_info=True)
        session.rollback()
        raise
    finally:
        session.close()


# ─── JSON Chat Export Importer (result.json) ───────────────────────────────────
def import_json_export(
    json_path: Path,
    channel_id: str,
    label: str | None = None,
    max_posts: int | None = None,
    dry_run: bool = False,
) -> int:
    """Parse and import a Telegram Desktop JSON export file (result.json)."""
    if not json_path.exists():
        logger.error("Export file not found: %s", json_path)
        sys.exit(1)

    logger.info("Loading export file: %s", json_path)

    with open(json_path, "r", encoding="utf-8") as f:
        try:
            export_data = json.load(f)
        except json.JSONDecodeError as exc:
            logger.error("Invalid JSON in export file: %s", exc)
            sys.exit(1)

    messages = export_data.get("messages", [])
    channel_name = export_data.get("name", channel_id)
    if not messages:
        logger.warning("No messages found in export file.")
        return 0

    text_messages = [
        msg for msg in messages
        if msg.get("type") == "message" and _extract_text_content(msg.get("text"))
    ]

    if max_posts and len(text_messages) > max_posts:
        text_messages = text_messages[-max_posts:]

    logger.info("Found %d text messages for %s", len(text_messages), channel_id)

    if dry_run:
        logger.info("[DRY RUN] Would import %d messages.", len(text_messages))
        return len(text_messages)

    session = SyncSessionLocal()
    run_id = uuid.uuid4()

    try:
        _ensure_monitored_channel(session, channel_id, channel_name)

        session.execute(
            pg_insert(IngestionRun).values(
                id=run_id,
                started_at=datetime.now(timezone.utc),
                platform="telegram",
                channel_ids=[channel_id],
                posts_collected=0,
                status="running",
                error_message=label or f"JSON Import from {json_path.name}",
            )
        )

        imported = 0
        skipped = 0

        for msg in text_messages:
            content_text = _extract_text_content(msg.get("text"))
            if not content_text:
                skipped += 1
                continue

            post_date = _parse_datetime(msg.get("date", ""))
            platform_post_id = f"{channel_id}_{msg['id']}"

            media_urls = None
            if msg.get("media_type"):
                media_urls = [{"type": msg["media_type"], "file_id": "desktop_export"}]

            stmt = (
                pg_insert(RawPost)
                .values(
                    platform="telegram",
                    platform_post_id=platform_post_id,
                    channel_id=channel_id,
                    author_id=_parse_from_id(msg.get("from_id")),
                    content_text=content_text,
                    content_language=None,
                    media_urls=media_urls,
                    reply_to_id=str(msg["reply_to_message_id"]) if msg.get("reply_to_message_id") else None,
                    forward_from_id=msg.get("forwarded_from"),
                    view_count=msg.get("views", 0) or 0,
                    reaction_counts=None,
                    ingested_at=datetime.now(timezone.utc),
                    posted_at=post_date,
                    ingestion_run_id=run_id,
                    processing_status="pending",
                )
                .on_conflict_do_nothing(constraint="uq_raw_posts_platform_post_id")
            )

            result = session.execute(stmt)
            if result.rowcount > 0:
                imported += 1
            else:
                skipped += 1

        session.execute(
            update(IngestionRun)
            .where(IngestionRun.id == run_id)
            .values(
                posts_collected=imported,
                status="completed",
                completed_at=datetime.now(timezone.utc),
            )
        )

        session.commit()
        logger.info("Import complete: %d inserted, %d skipped, run_id=%s", imported, skipped, run_id)
        return imported

    except Exception as exc:
        logger.error("Import failed: %s", exc, exc_info=True)
        session.rollback()
        raise
    finally:
        session.close()


# ─── Batch Directory Importer ──────────────────────────────────────────────────
def import_all_telegram_desktop(
    base_dir: Path,
    max_posts_per_channel: int | None = None,
    align_timestamps: bool = False,
    dry_run: bool = False,
) -> dict[str, int]:
    """Discover and import all exported channels in the given Telegram Desktop base folder."""
    if not base_dir.exists() or not base_dir.is_dir():
        logger.error("Base directory does not exist: %s", base_dir)
        return {}

    subdirs = sorted([d for d in base_dir.iterdir() if d.is_dir()])
    logger.info("Discovered %d potential export directories in %s", len(subdirs), base_dir)

    results: dict[str, int] = {}
    total_imported = 0

    for d in subdirs:
        # Check if it has result.json or messages*.html
        json_file = d / "result.json"
        html_files = list(d.glob("messages*.html"))

        if json_file.exists():
            channel_id = _slugify_channel_name(d.name)
            cnt = import_json_export(
                json_path=json_file,
                channel_id=channel_id,
                max_posts=max_posts_per_channel,
                dry_run=dry_run,
            )
            results[channel_id] = cnt
            total_imported += cnt
        elif html_files:
            cnt = import_html_export(
                export_dir=d,
                max_posts=max_posts_per_channel,
                dry_run=dry_run,
            )
            results[d.name] = cnt
            total_imported += cnt

    logger.info("Batch import completed: %d total posts across %d channels.", total_imported, len(results))

    if align_timestamps and not dry_run and total_imported > 0:
        logger.info("Running timestamp alignment (--align-timestamps) into active 48-hour trailing window...")
        try:
            from ingestion_a.backfill import run_offline_replay
            run_offline_replay()
            logger.info("Timestamps shifted into active window successfully.")
        except Exception as e:
            logger.warning("Could not automatically align timestamps: %s", e)

    return results


def main() -> None:
    """CLI entry point supporting single JSON, single HTML dir, or batch Telegram Desktop dir."""
    parser = argparse.ArgumentParser(
        prog="import_exported",
        description="Import Telegram Desktop chat exports (HTML or JSON) into SOCMINT database.",
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--import-all-dirs",
        type=Path,
        help="Path to base 'Telegram Desktop' folder containing multiple ChatExport folders.",
    )
    group.add_argument(
        "--import-dir",
        type=Path,
        help="Path to single ChatExport folder containing messages*.html files.",
    )
    group.add_argument(
        "--import-json",
        type=Path,
        help="Path to single result.json file.",
    )

    parser.add_argument(
        "--channel",
        type=str,
        default=None,
        help="Channel identifier (e.g. '@india_sentinel'). Auto-derived if omitted.",
    )
    parser.add_argument(
        "--max-posts",
        type=int,
        default=None,
        help="Maximum posts per channel to import (keeps latest N posts).",
    )
    parser.add_argument(
        "--align-timestamps",
        action="store_true",
        help="Automatically run offline timestamp replay after ingestion.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Count and preview without writing to database.",
    )
    parser.add_argument(
        "--label",
        type=str,
        default=None,
        help="Optional label for ingestion run.",
    )

    args = parser.parse_args()

    if args.import_all_dirs:
        results = import_all_telegram_desktop(
            base_dir=args.import_all_dirs,
            max_posts_per_channel=args.max_posts,
            align_timestamps=args.align_timestamps,
            dry_run=args.dry_run,
        )
        print(f"\n{'[DRY RUN] ' if args.dry_run else ''}Imported {sum(results.values())} posts across {len(results)} channels.")
        for ch, count in results.items():
            print(f"  - {ch}: {count} posts")

    elif args.import_dir:
        count = import_html_export(
            export_dir=args.import_dir,
            channel_id=args.channel,
            label=args.label,
            max_posts=args.max_posts,
            dry_run=args.dry_run,
        )
        print(f"\n{'[DRY RUN] ' if args.dry_run else ''}Processed {count} posts from {args.import_dir.name}")
        if args.align_timestamps and not args.dry_run and count > 0:
            from ingestion_a.backfill import run_offline_replay
            run_offline_replay()

    elif args.import_json:
        if not args.channel:
            print("[ERROR] --channel is required when importing a single JSON file.")
            sys.exit(1)
        count = import_json_export(
            json_path=args.import_json,
            channel_id=args.channel,
            label=args.label,
            max_posts=args.max_posts,
            dry_run=args.dry_run,
        )
        print(f"\n{'[DRY RUN] ' if args.dry_run else ''}Processed {count} posts from {args.channel}")
        if args.align_timestamps and not args.dry_run and count > 0:
            from ingestion_a.backfill import run_offline_replay
            run_offline_replay()


if __name__ == "__main__":
    main()
